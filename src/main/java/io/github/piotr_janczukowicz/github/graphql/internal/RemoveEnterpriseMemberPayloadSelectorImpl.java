import io.github.piotr_janczukowicz.github.graphql.model.UserSelector;
import java.util.function.Function;
import org.jspecify.annotations.Nullable;

/** Reads and records the fields of {@code RemoveEnterpriseMemberPayload}; used by the generated selection code only. */
final class RemoveEnterpriseMemberPayloadSelectorImpl implements RemoveEnterpriseMemberPayloadSelector {

    private final Cursor cursor;

    RemoveEnterpriseMemberPayloadSelectorImpl(final Cursor cursor) {
        this.cursor = cursor;
    }

    @Override
    public @Nullable String clientMutationId() {
        return cursor.get("clientMutationId", ScalarType.STRING);
    }

    @Override
    public <R> @Nullable R enterprise(final Function<EnterpriseSelector, R> selection) {
        return cursor.object("enterprise", child -> selection.apply(new EnterpriseSelectorImpl(child)));
    }

    @Override
    public <R> @Nullable R user(final Function<UserSelector, R> selection) {
        return cursor.object("user", child -> selection.apply(new UserSelectorImpl(child)));
    }

    @Override
    public <R> @Nullable R viewer(final Function<UserSelector, R> selection) {
        return cursor.object("viewer", child -> selection.apply(new UserSelectorImpl(child)));
    }
}
